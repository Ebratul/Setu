def write_files() -> list[Path]:
    written: list[Path] = []

    def put(rel: str, data: bytes) -> None:
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written.append(path)

    for b in BUYERS:
        docs = files.buyer_documents(b)
        for name, data in docs.items():
            put(f"onboarding/buyer-{b.n}/{name}", data)
        put(
            f"onboarding/buyer-{b.n}/trade_licence_photo.jpg",
            files.as_scan(docs["1_trade_licence.pdf"], fmt="jpg"),
        )
    for s in SUPPLIERS:
        docs = files.supplier_documents(s)
        for name, data in docs.items():
            put(f"onboarding/supplier-{s.n}/{name}", data)
        put(
            f"onboarding/supplier-{s.n}/business_licence_photo.png",
            files.as_scan(docs["1_business_licence.pdf"], fmt="png"),
        )
    for o in ORDERS:
        for name, data in files.order_files(o).items():
            put(f"orders/order-{o.n}/{name}", data)
    for name, _verdict, text in files.EMAILS:
        put(f"emails/{name}", text.encode())
    for name, data in files.bad_files().items():
        put(f"negative/{name}", data)
    for src, dst in (
        ("bill_of_lading_forged.pdf", "bill_of_lading_forged.pdf"),
        ("proforma_invoice_resaved.pdf", "proforma_invoice_resaved.pdf"),
        ("prefinanced_invoice.pdf", "prefinanced_invoice.pdf"),
    ):
        put(f"negative/{dst}", (DEMO_DIR / src).read_bytes())
    return written


def cell(value: str) -> str:
    text = value.replace("|", "\\|")
    if value.startswith(LINK_PREFIXES):
        target = f"../frontend/public/demo-files/{value}"
        label = value.rsplit("/", 1)[-1] or value.rstrip("/").rsplit("/", 1)[-1] + "/"
        return f"[{label}]({target})"
    return text if text else "-"


def table(form: Form) -> str:
    head = "| Field | " + " | ".join(form.heads) + " |"
    sep = "|---|" + "---|" * len(form.heads)
    body = [
        "| " + " | ".join([f"**{label}**", *(cell(v) for v in values)]) + " |"
        for label, values in form.rows
    ]
    return "\n".join([head, sep, *body])


