def anchor(title: str) -> str:
    """GitHub-style heading anchor: lower case, punctuation dropped, spaces become hyphens."""
    kept = "".join(c for c in title.lower() if c.isalnum() or c in " -")
    return kept.replace(" ", "-")


def render_index(paths: list[Path]) -> str:
    rows: dict[str, list[str]] = {}
    for p in sorted(paths):
        rel = p.relative_to(OUT)
        rows.setdefault(str(rel.parent), []).append(rel.name)
    parts = [
        '<!doctype html><html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        "<title>Setu demo files</title>",
        "<style>body{font:16px/1.5 system-ui,sans-serif;max-width:56rem;margin:0 auto;padding:1rem 16px 3rem;color:#1b1f23;background:#fff}",
        "@media(prefers-color-scheme:dark){body{background:#14181c;color:#e6e8ea}a{color:#8ab4ff}}",
        "h1{font-size:1.5rem}h2{font-size:1.05rem;margin-top:1.6rem;border-bottom:1px solid #8884}ul{padding-left:1.2rem}li{margin:.15rem 0}</style></head><body>",
        "<h1>Setu demo files</h1>",
        "<p>Fictional sample PDFs, pictures and e-mails for the demo forms. Each carries a SAMPLE mark; none is a real document. "
        "The values to type with them are in <code>docs/demo-form-data.md</code>.</p>",
    ]
    for folder, names in rows.items():
        parts.append(f"<h2>{html.escape(folder)}</h2><ul>")
        parts += [
            f'<li><a href="{html.escape(folder)}/{html.escape(n)}">{html.escape(n)}</a></li>'
            for n in names
        ]
        parts.append("</ul>")
    parts.append("</body></html>")
    return "\n".join(parts)


def main() -> None:
    written = write_files()
    (OUT / "index.html").write_text(render_index(written), encoding="utf-8")
    DOC.write_text(render_doc(), encoding="utf-8")
    print(f"wrote {len(written)} files to {OUT} and {DOC}")


if __name__ == "__main__":
    main()
