"""Export the active financing catalogue (financing_options) to a KB source, so the knowledge base
never drifts from the DB. Deterministic output: same rows → same bytes (no timestamps)."""

from decimal import Decimal
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import FinancingOption, Party
from app.domain.money import q2

OUT_NAME = "financing-catalogue.md"
SOURCE_ID = "financing-catalogue"


def _pct(x: Decimal | None) -> str | None:
    return None if x is None else f"{(x * 100).normalize():f}%"


def _money(x: Decimal | None, ccy: str) -> str | None:
    return None if x is None else f"{ccy} {q2(x):,.2f}"


def _one_line(value: str) -> str:
    """DB text may not add headings, front-matter fences or list items to the KB source."""
    return " ".join(value.split()).lstrip("#-> ").replace("---", "—")


def _tenor(o: FinancingOption) -> str:
    if o.tenor_rule:
        return o.tenor_rule.replace("_", " ").lower()
    if o.tenor_days_min and o.tenor_days_max and o.tenor_days_min != o.tenor_days_max:
        return f"{o.tenor_days_min} to {o.tenor_days_max} days"
    days = o.tenor_days_max or o.tenor_days_min
    return f"{days} days" if days else "not fixed"


def render(db: Session, reviewed: str) -> str:
    rows = db.execute(
        select(FinancingOption, Party.legal_name)
        .outerjoin(Party, Party.id == FinancingOption.provider_party_id)
        .where(FinancingOption.active.is_(True))
        .order_by(FinancingOption.code)
    ).all()
    lines = [
        "---",
        f"id: {SOURCE_ID}",
        "title: Setu financing catalogue (generated)",
        "source_type: catalogue",
        'original_reference: "Setu demo financing_options table (generated by npm run kb:sync)"',
        "language: en",
        f"last_reviewed: {reviewed}",
        'disclaimer: "Fictional demo providers and simulated terms. Generated from the database; '
        'do not edit by hand."',
        "---",
        "# Setu financing catalogue (generated)",
        "",
        "These are the financing options in Setu's simulated demo catalogue. All providers are "
        "fictional. Which option is best for a deal depends on eligibility and total cost; ask "
        "Setu to compare options for a specific deal.",
    ]
    for o, provider in rows:
        ccy = o.currency
        facts = [
            ("Kind", str(o.kind).replace("_", " ").lower()),
            ("Provider", provider),
            ("Annual rate", _pct(o.annual_rate)),
            ("Flat cost", _pct(o.flat_cost_rate)),
            ("Price uplift", _pct(o.price_uplift_rate)),
            ("Fee", _pct(o.fee_rate)),
            ("Fixed fee", _money(o.fee_fixed, ccy)),
            ("Tenor", _tenor(o)),
            ("Minimum amount", _money(o.min_amount, ccy)),
            ("Maximum amount", _money(o.max_amount, ccy)),
            ("Collateral", o.collateral),
            ("Conditions", o.conditions),
        ]
        lines += ["", f"## {_one_line(o.name)}", ""]
        lines += [f"- {k}: {_one_line(v)}" for k, v in facts if v]
    return "\n".join(lines) + "\n"


def sync(db: Session, out_dir: Path, reviewed: str) -> tuple[Path, bool]:
    """Write the catalogue; returns (path, changed)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / OUT_NAME
    body = render(db, reviewed)
    changed = not path.exists() or path.read_text(encoding="utf-8") != body
    if changed:
        path.write_text(body, encoding="utf-8")
    return path, changed
